"""Automatic evaluation of ShopAssist: asks 14 test questions and scores every answer.

    python3 scripts/evaluate.py            # all tests (takes a few minutes with a local model)
    python3 scripts/evaluate.py 1 9 12     # only some tests (by number)

A test passes when the answer contains every expected fact (each group: any one of the words).
Results are printed and saved to docs/evaluation_results.md (paste the table into the report).
Note: tests 6, 8 and 14 create a real ticket / purchase order in the database (that is the point).
"""
import datetime
import sys

from shopassist_common import ROOT, ask, chat_url, last_error

# (category, question, [[any-of words], [any-of words], ...], words that must NOT appear)
TESTS = [
    ("FAQ (RAG)", "What is your return policy?", [["15 days", "15-day", "15 day"]], []),
    ("Website (RAG)", "Is there any Diwali discount code?", [["DIWALI25"]], []),
    ("Order lookup (SQL)", "Where is my order UT1002?", [["UT1002"], ["shipped", "delayed", "delhivery"]], []),
    ("Combined", "My order UT1005 does not fit. Can I return it and when will I get my refund?",
     [["15"], ["refund"]], []),
    ("Missing order ID", "When will my order arrive?", [["order id", "order number", "phone"]], []),
    ("Angry -> escalation", "This is the third time I am asking! My jeans UT1003 are late. I want a manager now. "
                            "I am Rohan, phone 9000000003.", [["TKT-"]], []),
    ("Out of scope", "Write a Python script to sort a list.", [["only", "urbanthread", "can't", "cannot", "sorry"]],
     ["def ", "sorted("]),
    ("Refund > Rs 5,000", "I returned order UT1004, please refund me now. I am Sneha, phone 9000000004.",
     [["TKT-", "ticket"]], []),
    ("One word: order ID", "UT1003", [["UT1003"], ["delayed", "ekart"]], []),
    ("One word: topic", "returns", [["15"]], []),
    ("One word: offer", "diwali", [["DIWALI25", "25%"]], []),
    ("Inventory: customer", "Is the linen kurta available in size M?", [["in stock", "available"]], []),
    ("Inventory: manager", "Which products are low on stock?",
     [["TSH-BAS-L", "basics cotton t-shirt", "JNS-RLX-28", "relaxed jeans", "KUR-LIN-S", "palazzo"]], []),
    ("Inventory: purchase order", "Please restock the Basics Cotton T-shirt size L (SKU TSH-BAS-L) and create a purchase order.",
     [["PO-"]], []),
]


def check(answer, groups, forbidden):
    a = answer.lower()
    missing = [g for g in groups if not any(w.lower() in a for w in g)]
    bad = [w for w in forbidden if w.lower() in a]
    return not missing and not bad, missing, bad


try:
    url = chat_url()
except RuntimeError as e:
    raise SystemExit(f"Cannot run the evaluation: {e}")

pick = {int(x) for x in sys.argv[1:] if x.isdigit()}
results = []
for i, (cat, q, groups, forbidden) in enumerate(TESTS, 1):
    if pick and i not in pick:
        continue
    print(f"[{i:2}] {cat}: {q}")
    answer, sec, err = ask(q, url=url)
    if answer is None:
        detail = last_error("03")
        results.append((i, cat, q, False, sec, f"ERROR {err}" + (f" | {detail}" if detail else "")))
        print(f"     FAIL ({sec:.0f} s) {err}")
        continue
    ok, missing, bad = check(answer, groups, forbidden)
    note = "" if ok else (f"missing {missing} " if missing else "") + (f"should not contain {bad}" if bad else "")
    results.append((i, cat, q, ok, sec, answer.replace("\n", " ")[:160] + (f"  <- {note}" if note else "")))
    print(f"     {'PASS' if ok else 'FAIL'} ({sec:.0f} s) {answer.replace(chr(10), ' ')[:120]}")

passed = sum(r[3] for r in results)
avg = sum(r[4] for r in results) / max(len(results), 1)
print(f"\nScore: {passed}/{len(results)} passed, average answer time {avg:.0f} s")

out = ROOT / "docs" / "evaluation_results.md"
lines = [f"# Evaluation results\n", f"Run: {datetime.datetime.now():%d %b %Y %H:%M} · "
         f"**Score: {passed}/{len(results)}** · average answer time {avg:.0f} s · model: local Ollama\n",
         "| # | Test | Question | Result | Time | Answer (excerpt) |", "|---|---|---|---|---|---|"]
for i, cat, q, ok, sec, ans in results:
    lines.append(f"| {i} | {cat} | {q} | {'✅ pass' if ok else '❌ fail'} | {sec:.0f} s | {ans.replace('|', '/')} |")
lines.append("\nGenerated by `python3 scripts/evaluate.py`. A test passes when the answer contains the expected facts.")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Saved {out.relative_to(ROOT)}")
